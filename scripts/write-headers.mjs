// Runs after `next build`. Turns security-headers.json into host config files
// inside out/: .htaccess for NameHero (Apache/LiteSpeed) and _headers for
// Netlify/Cloudflare Pages style hosts. The form endpoint's origin is added to
// the CSP automatically so the Contact form keeps working when it is set.
import fs from "node:fs";

try {
  process.loadEnvFile(".env.local");
} catch {
  // No local env file: CI and hosts pass values through the environment.
}

const config = JSON.parse(fs.readFileSync("security-headers.json", "utf8"));
const csp = structuredClone(config.contentSecurityPolicy);

const endpoint = process.env.NEXT_PUBLIC_FORM_ENDPOINT;
if (endpoint) {
  const { origin } = new URL(endpoint);
  csp["connect-src"].push(origin);
  csp["form-action"].push(origin);
}

const cspValue = Object.entries(csp)
  .map(([directive, values]) => `${directive} ${values.join(" ")}`)
  .join("; ");

const headers = { "Content-Security-Policy": cspValue, ...config.headers };

const htaccess = `# Generated by scripts/write-headers.mjs from security-headers.json. Do not edit.
Options -Indexes
ErrorDocument 404 /404.html

<IfModule mod_headers.c>
${Object.entries(headers)
  .map(([name, value]) => `  Header always set ${name} "${value}"`)
  .join("\n")}
  <FilesMatch "\\.(js|css|woff2)$">
    Header set Cache-Control "public, max-age=31536000, immutable"
  </FilesMatch>
  <FilesMatch "\\.(webp|jpg|svg)$">
    Header set Cache-Control "public, max-age=604800"
  </FilesMatch>
  <FilesMatch "\\.(html|xml|txt)$">
    Header set Cache-Control "public, max-age=0, must-revalidate"
  </FilesMatch>
</IfModule>
`;

const netlify = `/*\n${Object.entries(headers)
  .map(([name, value]) => `  ${name}: ${value}`)
  .join("\n")}\n`;

fs.writeFileSync("out/.htaccess", htaccess);
fs.writeFileSync("out/_headers", netlify);
console.log("Wrote out/.htaccess and out/_headers");
